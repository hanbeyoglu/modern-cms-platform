INSERT INTO "_StoreCategoryMallMap" ("legacyId", "mallId", "newId")
SELECT
  sc.id,
  m.id,
  'sc_' || substr(md5(sc.id || ':' || m.id), 1, 24)
FROM "StoreCategory" sc
CROSS JOIN "Mall" m
WHERE sc."tenantId" IS NULL AND sc."deletedAt" IS NULL;

INSERT INTO "StoreCategory" (
  id, "tenantId", "mallId", name, description, "normalizedName", slug, "slugAutoGenerated",
  "sortOrder", active, "iconMediaId", "createdAt", "updatedAt", "deletedAt"
)
SELECT
  map."newId",
  m."tenantId",
  m.id,
  sc.name,
  NULL,
  lower(trim(regexp_replace(translate(sc.name, 'İIıŞşĞğÜüÖöÇç', 'iiisssgguuuooocc'), '\s+', ' ', 'g'))),
  sc.slug || '-' || substr(md5(m.id || ':' || sc.id), 1, 8),
  true,
  sc."sortOrder",
  CASE WHEN sc.status = 'ACTIVE' THEN true ELSE false END,
  NULL,
  CURRENT_TIMESTAMP,
  CURRENT_TIMESTAMP,
  sc."deletedAt"
FROM "_StoreCategoryMallMap" map
JOIN "StoreCategory" sc ON sc.id = map."legacyId"
JOIN "Mall" m ON m.id = map."mallId"
WHERE NOT EXISTS (SELECT 1 FROM "StoreCategory" existing WHERE existing.id = map."newId");

