-- Resolve duplicate normalized names per mall
WITH ranked AS (
  SELECT
    id,
    "normalizedName",
    "mallId",
    ROW_NUMBER() OVER (
      PARTITION BY "mallId", "normalizedName"
      ORDER BY ("deletedAt" IS NULL) DESC, "createdAt" ASC, id ASC
    ) AS rn
  FROM "StoreCategory"
  WHERE "mallId" IS NOT NULL
)
UPDATE "StoreCategory" sc
SET "normalizedName" = sc."normalizedName" || '-' || r.rn
FROM ranked r
WHERE sc.id = r.id AND r.rn > 1;

