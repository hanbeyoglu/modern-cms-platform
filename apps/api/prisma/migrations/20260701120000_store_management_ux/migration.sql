UPDATE "GlobalStore"
SET "normalizedName" = lower(trim(regexp_replace(
  translate(
    "name",
    'İIıŞşĞğÜüÖöÇç',
    'iiisssgguuuooocc'
  ),
  '\s+', ' ', 'g'
)))
WHERE "normalizedName" IS NULL;

UPDATE "GlobalStore"
SET "normalizedName" = "id"
WHERE "normalizedName" IS NULL OR "normalizedName" = '';

-- Resolve duplicate normalized names (e.g. legacy seed data) before unique index
WITH ranked AS (
  SELECT
    id,
    "normalizedName",
    ROW_NUMBER() OVER (
      PARTITION BY "normalizedName"
      ORDER BY ("deletedAt" IS NULL) DESC, "createdAt" ASC, id ASC
    ) AS rn
  FROM "GlobalStore"
)
UPDATE "GlobalStore" g
SET "normalizedName" = g."normalizedName" || '-' || r.rn
FROM ranked r
WHERE g.id = r.id
  AND r.rn > 1;

ALTER TABLE "GlobalStore" ALTER COLUMN "normalizedName" SET NOT NULL;
CREATE UNIQUE INDEX "GlobalStore_normalizedName_key" ON "GlobalStore"("normalizedName");

