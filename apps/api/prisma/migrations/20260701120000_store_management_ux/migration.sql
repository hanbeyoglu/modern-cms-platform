INSERT INTO "MallFloor" ("id", "tenantId", "mallId", "name", "label", "sortOrder", "active", "createdAt", "updatedAt")
SELECT
  'mf_' || substr(md5("mallId" || ':' || trim("floor")), 1, 24),
  "tenantId",
  "mallId",
  trim("floor"),
  trim("floor"),
  row_number() OVER (PARTITION BY "mallId" ORDER BY trim("floor")) - 1,
  true,
  CURRENT_TIMESTAMP,
  CURRENT_TIMESTAMP
FROM "MallStore"
WHERE "floor" IS NOT NULL AND trim("floor") <> '' AND "deletedAt" IS NULL
GROUP BY "tenantId", "mallId", trim("floor");

